export const mockApi = {
  async request(method, path, data) {
    if (path === '/auth/login' || path === '/auth/signup' || path === '/auth/reset-password' || path === '/auth/forgot-password') {
      if (data?.email) currentUser = { ...currentUser, email: data.email, name: data.name || currentUser.name };
      return { user: clone(currentUser), token: 'mock-access-token', message: 'Password reset successfully.' };
    }
    if (path === '/auth/me') {
      if (method === 'PATCH') Object.assign(currentUser, clone(data));
      return clone(currentUser);
    }
    if (method === 'GET' && path === '/dashboard') {
      return {
        greeting: `Hey ${currentUser.name}`, user: clone(currentUser), units: units.map((unit) => ({ ...clone(unit), topics: clone(topics.filter((topic) => topic.unitId === unit.id)) })),
        topics: clone(topics.filter((topic) => topic.unitId == null)), tasks: topics.map((topic) => ({ topicId: topic.id, title: topic.title, tasks: [
          { id: 'material', title: 'Add material', done: topic.topicFiles.length > 0 },
          { id: 'explain', title: 'Explain it', done: topic.mastery >= currentUser.passMark },
          { id: 'pin', title: 'Pin it', done: places.some((place) => place.flags.some((flag) => flag.topicId === topic.id)) },
          { id: 'recall', title: 'Recall it', done: false },
        ] })),
        exams: exams.map((exam) => ({ ...clone(exam), unit: clone(units.find((unit) => unit.id === exam.unitId) ?? null) })),
        nearest_exam: exams[0] ? { ...clone(exams[0]), unit: clone(units.find((unit) => unit.id === exams[0].unitId) ?? null), days_left: 14, tone: 'calm' } : null,
        pass_mark: currentUser.passMark, streak_days: 3,
      };
    }

    if (path === '/units') {
      if (method === 'GET') return clone(units);
      if (method === 'POST') { const unit = { id: next.unit++, ...clone(data) }; units.push(unit); return clone(unit); }
    }
    const unitMatch = match(path, 'units');
    if (unitMatch) {
      const unit = units.find((item) => item.id === unitMatch.id);
      if (!unit) throw new Error('Unit not found.');
      if (method === 'PATCH') { Object.assign(unit, clone(data)); return clone(unit); }
      if (method === 'DELETE') { units.splice(units.indexOf(unit), 1); return null; }
    }

    if (path === '/topics') {
      if (method === 'GET') return clone(topics);
      if (method === 'POST') {
        const topic = { id: next.topic++, ...clone(data), unitId: data.unitId ?? null, notes: data.notes ?? '', keyPoints: data.keyPoints ?? [], mastery: 0, topicFiles: [], explanations: [] };
        topics.unshift(topic);
        return clone(topic);
      }
    }
    const topicMatch = match(path, 'topics');
    if (topicMatch) {
      const topic = getTopic(topicMatch.id);
      if (!topic) throw new Error('Topic not found.');
      if (topicMatch.suffix === 'explanations' && method === 'GET') return clone(topic.explanations);
      if ((topicMatch.suffix === 'files' || topicMatch.suffix === 'extract') && method === 'POST') {
        const files = data?.getAll?.('files') ?? [];
        if (!files.length) throw new Error('Choose at least one PDF or image.');
        const addedPages = files.reduce((sum, file) => sum + (file.type === 'application/pdf' ? 2 : 1), 0);
        const existingPages = topic.topicFiles.reduce((sum, file) => sum + file.pageCount, 0);
        if (existingPages + addedPages > 100) throw new Error('A topic can contain no more than 100 pages total.');
        const file = files[0];
        const extraction = fakeExtraction(file?.name);
        topic.title = extraction.title;
        topic.notes = extraction.notes;
        topic.keyPoints = extraction.keyPoints;
        files.forEach((source, index) => topic.topicFiles.push({ id: 800 + topic.topicFiles.length + index + 1, fileUrl: '', type: source.type || 'image/jpeg', pageCount: source.type === 'application/pdf' ? 2 : 1 }));
        return { topic: clone(topic), extraction };
      }
      if (topicMatch.suffix.startsWith('files/') && method === 'DELETE') {
        const fileId = Number(topicMatch.suffix.split('/')[1]);
        topic.topicFiles = topic.topicFiles.filter((file) => file.id !== fileId);
        return null;
      }
      if (topicMatch.suffix === 'explain' && method === 'POST') {
        if (!topic.keyPoints.length) throw new Error('Add key points to this topic before explaining it.');
        if (data.transcript.trim().split(/\s+/).length < 15) throw new Error('Please explain a little more before checking your understanding (at least 15 words).');
        const transcript = data.transcript.toLowerCase();
        const resultPoints = topic.keyPoints.map((point) => {
          const words = point.text.toLowerCase().split(/\W+/).filter((word) => word.length > 4);
          const covered = words.filter((word) => transcript.includes(word)).length;
          const status = covered >= Math.max(1, words.length * 0.6) ? 'covered' : covered ? 'partial' : 'missing';
          return { id: point.id, status, evidence: '', feedback: status === 'covered' ? 'You explained this idea clearly.' : status === 'partial' ? 'Add more detail about this idea.' : 'Revisit this idea and explain it in your own words.' };
        });
        const score = Math.round(resultPoints.reduce((sum, point) => sum + (point.status === 'covered' ? 1 : point.status === 'partial' ? 0.5 : 0), 0) / resultPoints.length * 100);
        const explanation = { id: next.explanation++, score, transcript: data.transcript, points: resultPoints, summary: 'Mock explanation check complete.', next_focus: resultPoints.filter((point) => point.status !== 'covered').slice(0, 2).map((point) => point.id), createdAt: new Date().toISOString() };
        explanations.unshift(explanation);
        topic.explanations.unshift(explanation);
        topic.mastery = score;
        return clone(explanation);
      }
      if (topicMatch.suffix === '' && method === 'GET') return clone(topic);
      if (topicMatch.suffix === '' && method === 'PATCH') { Object.assign(topic, clone(data)); return clone(topic); }
      if (topicMatch.suffix === '' && method === 'DELETE') { topics.splice(topics.indexOf(topic), 1); return null; }
    }
    const explanationMatch = match(path, 'explanations');
    if (explanationMatch && method === 'GET') {
      const explanation = explanations.find((item) => item.id === explanationMatch.id);
      if (!explanation) throw new Error('Explanation not found.');
      return clone(explanation);
    }

    if (method === 'GET' && path === '/places') return places.map(countPlace);
    const placeMatch = match(path, 'places');
    if (placeMatch) {
      const place = places.find((item) => item.id === placeMatch.id);
      if (method === 'GET') { if (!place) throw new Error('Place not found.'); return clone(place); }
      if (method === 'PATCH') { if (!place) throw new Error('Place not found.'); place.name = data.name.trim(); return clone(place); }
      if (method === 'DELETE') { if (!place) throw new Error('Place not found.'); places.splice(places.indexOf(place), 1); return null; }
    }
    if (method === 'POST' && path === '/places') {
      const name = data.get('name')?.trim();
      if (!name) throw new Error('Place name is required.');
      const place = { id: next.place++, name, imageUrl: svgImage(name, '#91b0a3', '#526e5c'), flags: [] };
      places.unshift(place);
      return countPlace(place);
    }
    if (method === 'POST' && path === '/flags') {
      const form = data instanceof FormData ? Object.fromEntries(data.entries()) : clone(data);
      if (!Number.isInteger(Number(form.placeId)) || !Number.isFinite(Number(form.x)) || Number(form.x) < 0 || Number(form.x) > 100 || !Number.isFinite(Number(form.y)) || Number(form.y) < 0 || Number(form.y) > 100) throw new Error('Flag coordinates must be between 0 and 100.');
      if (!form.title?.trim() || form.title.trim().length > 120) throw new Error('Flag title must be between 1 and 120 characters.');
      const place = places.find((item) => item.id === Number(form.placeId));
      if (!place) throw new Error('Place not found.');
      const flag = { ...form, id: next.flag++, placeId: Number(form.placeId), x: Number(form.x), y: Number(form.y), topicId: form.topicId ? Number(form.topicId) : null, keyPointId: form.keyPointId ? Number(form.keyPointId) : null };
      place.flags.push(flag);
      return clone(flag);
    }
    const flagMatch = match(path, 'flags');
    if (flagMatch) {
      const place = places.find((item) => item.flags.some((flag) => flag.id === flagMatch.id));
      const flag = place?.flags.find((item) => item.id === flagMatch.id);
      if (!flag) throw new Error('Flag not found.');
      if (method === 'PATCH') { Object.assign(flag, clone(data)); return clone(flag); }
      if (method === 'DELETE') { place.flags.splice(place.flags.indexOf(flag), 1); return null; }
    }

    if (path === '/exams') {
      if (method === 'GET') return exams.map((exam) => ({ ...clone(exam), unit: clone(units.find((unit) => unit.id === exam.unitId) ?? null) }));
      if (method === 'POST') { const exam = { id: next.exam++, ...clone(data), examDate: data.exam_date, unitId: data.unitId ?? null }; exams.push(exam); return clone(exam); }
    }
    const examMatch = match(path, 'exams');
    if (examMatch) {
      const exam = exams.find((item) => item.id === examMatch.id);
      if (!exam) throw new Error('Exam not found.');
      if (method === 'PATCH') { Object.assign(exam, clone(data)); if (data.exam_date) exam.examDate = data.exam_date; return clone(exam); }
      if (method === 'DELETE') { exams.splice(exams.indexOf(exam), 1); return null; }
    }

    if (path === '/recall/start' && method === 'POST') {
      const candidates = places.filter((place) => place.flags.length > 0);
      if (!candidates.length) throw new Error('Add a place and at least one flag before starting Recall.');
      const place = candidates[Math.floor(Math.random() * candidates.length)];
      const round = { id: next.round++, placeId: place.id, timeLimitSec: data.time_limit_sec || 30, startedAt: new Date().toISOString(), results: [], finishedAt: null };
      recallRounds.unshift(round);
      return { roundId: round.id, time_limit_sec: round.timeLimitSec, place: { id: place.id, name: place.name, imageUrl: place.imageUrl }, flags: place.flags.map(({ id, x, y }) => ({ id, x, y })) };
    }
    if (path === '/recall/history' && method === 'GET') return clone(recallRounds);
    const recallMatch = path.match(/^\/recall\/(\d+)\/(reveal|result|finish)$/);
    if (recallMatch) {
      const roundId = Number(recallMatch[1]);
      const action = recallMatch[2];
      const round = recallRounds.find((item) => item.id === roundId);
      if (!round) throw new Error('Recall round not found.');
      const place = places.find((item) => item.id === round.placeId);
      if (action === 'reveal' && method === 'POST') {
        const flag = place?.flags.find((item) => item.id === Number(data.flag_id));
        if (!flag) throw new Error('Flag not found.');
        return { id: flag.id, title: flag.title, note: flag.note, emoji: flag.emoji };
      }
      if (action === 'result' && method === 'POST') {
        const result = data.result === 'green' && data.seconds_taken <= round.timeLimitSec ? 'green' : 'red';
        round.results.push({ flagId: data.flag_id, result, secondsTaken: data.seconds_taken });
        return { flag_id: data.flag_id, result, seconds_taken: data.seconds_taken };
      }
      if (action === 'finish' && method === 'POST') {
        const results = place.flags.map((flag) => round.results.find((item) => item.flagId === flag.id) || { flagId: flag.id, result: 'red', secondsTaken: round.timeLimitSec });
        round.results = results;
        round.finishedAt = new Date().toISOString();
        return {
          roundId: round.id,
          place: { id: place.id, name: place.name, imageUrl: place.imageUrl },
          flags: clone(place.flags),
          results,
          summary: { green: results.filter((item) => item.result === 'green').length, red: results.filter((item) => item.result === 'red').length },
        };
      }
    }
    throw new Error(`Mock API does not handle ${method} ${path}.`);
  },
};
